import '../models/tube_model.dart';

enum SolveOutcome { solved, unsolvable, searchLimitReached }

class SolveReport {
  const SolveReport({
    required this.outcome,
    required this.statesExplored,
    this.pours,
  });

  final SolveOutcome outcome;

  /// Shortest number of pours that finishes the board, only set when solved.
  final int? pours;
  final int statesExplored;

  bool get isSolvable => outcome == SolveOutcome.solved;

  /// The search could not prove either way, so the caller must fall back to
  /// whatever it already knew about the position.
  bool get isConclusive => outcome != SolveOutcome.searchLimitReached;

  @override
  String toString() =>
      'SolveReport($outcome, pours: $pours, explored: $statesExplored)';
}

/// Breadth-first solver for a water-sort board.
///
/// Tube order never matters to the puzzle, so states are canonicalised by
/// sorting their tubes before they hit the visited set. That single step is
/// what keeps a 10+ colour board inside a usable node budget.
class WaterSortSolver {
  /// Levels are generated by undoing legal pours, so anything the budget cannot
  /// prove is still assumed winnable rather than thrown away.
  static const int defaultNodeBudget = 60000;

  static SolveReport solve(
    List<Tube> tubes, {
    int nodeBudget = defaultNodeBudget,
  }) {
    final start = _State.from(tubes);
    if (start.isSolved) {
      return SolveReport(
        outcome: SolveOutcome.solved,
        statesExplored: 0,
        pours: 0,
      );
    }

    final visited = <String>{start.key};
    var frontier = <_State>[start];
    var depth = 0;
    var explored = 0;

    while (frontier.isNotEmpty) {
      depth++;
      final next = <_State>[];
      for (final state in frontier) {
        for (final move in state.legalMoves()) {
          final moved = state.apply(move);
          if (moved.isSolved) {
            return SolveReport(
              outcome: SolveOutcome.solved,
              statesExplored: explored,
              pours: depth,
            );
          }
          final key = moved.key;
          if (visited.add(key)) {
            next.add(moved);
            explored++;
            if (explored >= nodeBudget) {
              return SolveReport(
                outcome: SolveOutcome.searchLimitReached,
                statesExplored: explored,
              );
            }
          }
        }
      }
      frontier = next;
    }

    return SolveReport(
      outcome: SolveOutcome.unsolvable,
      statesExplored: explored,
    );
  }
}

class PourMove {
  const PourMove(this.from, this.to, this.amount);

  final int from;
  final int to;
  final int amount;
}

class _State {
  _State._(this.capacity, this.tubes);

  factory _State.from(List<Tube> source) {
    return _State._(
      // Every gameplay tube shares a capacity, so the first one defines it.
      source.isEmpty ? 4 : source.first.capacity,
      [
        for (final tube in source)
          [for (final color in tube.colors) color.toARGB32()],
      ],
    );
  }

  final int capacity;
  final List<List<int>> tubes;

  String get key {
    final parts = <String>[];
    for (final tube in tubes) {
      parts.add(tube.isEmpty ? '' : tube.join(','));
    }
    parts.sort();
    return parts.join('#');
  }

  bool get isSolved {
    for (final tube in tubes) {
      if (tube.isEmpty) continue;
      if (tube.length < capacity) return false;
      final first = tube.first;
      for (final color in tube) {
        if (color != first) return false;
      }
    }
    return true;
  }

  int _topRun(int index) {
    final tube = tubes[index];
    if (tube.isEmpty) return 0;
    final color = tube.last;
    var run = 0;
    for (var i = tube.length - 1; i >= 0 && tube[i] == color; i--) {
      run++;
    }
    return run;
  }

  /// Legal pours, with the moves that cannot make progress filtered out:
  /// a finished tube, parking a uniform tube into an empty tube, and duplicate
  /// pours into interchangeable empty tubes.
  List<PourMove> legalMoves() {
    final moves = <PourMove>[];

    for (var from = 0; from < tubes.length; from++) {
      final source = tubes[from];
      if (source.isEmpty) continue;
      final run = _topRun(from);
      if (source.length == capacity && run == capacity) continue;
      final sourceIsWholeRun = source.length == run;

      var emptyTargetTaken = false;
      for (var to = 0; to < tubes.length; to++) {
        if (to == from) continue;
        final target = tubes[to];
        if (target.length >= capacity) continue;

        if (target.isEmpty) {
          if (emptyTargetTaken || sourceIsWholeRun) continue;
          emptyTargetTaken = true;
          moves.add(PourMove(from, to, run));
        } else if (target.last == source.last) {
          final room = capacity - target.length;
          moves.add(PourMove(from, to, run < room ? run : room));
        }
      }
    }
    return moves;
  }

  _State apply(PourMove move) {
    final copied = _State._(capacity, [
      for (final tube in tubes) List<int>.of(tube),
    ]);
    final color = copied.tubes[move.from].last;
    for (var i = 0; i < move.amount; i++) {
      copied.tubes[move.from].removeLast();
      copied.tubes[move.to].add(color);
    }
    return copied;
  }
}
